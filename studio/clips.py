"""Clip manifest and batch renderer.  python3 studio/clips.py [render|manifest] [name ...]

Each exercise maps to one clip (or a left/right pair). Rep exercises loop once per rep, so the app can
play them at (loop length / reps per loop) / rep tempo and stay in step with the spoken count.
"""
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "public", "clips")
RES, FPS, JOBS = "800x450", "24", 3

# exercise id -> (motion, loop seconds, reps per loop) or (None, ...) for left/right pairs {side: motion}
SINGLE = {
    "march": ("march", 2.0, 1), "brisk_walk": ("brisk_walk", 1.6, 0), "gentle_walk": ("gentle_walk", 2.6, 0),
    "hip_circles": ("hip_circles", 4.0, 1), "arm_circles": ("arm_circles", 4.0, 1), "shoulder_rolls": ("shoulder_rolls", 4.0, 1),
    "bw_squat": ("bw_squat", 4.0, 1), "band_squat": ("band_squat", 4.0, 1), "band_rdl": ("band_rdl", 4.0, 1),
    "band_deadlift": ("band_deadlift", 4.0, 1), "glute_bridge": ("glute_bridge", 4.0, 1), "dead_bug": ("dead_bug", 8.0, 2),
    "sit_to_stand": ("sit_to_stand", 4.0, 1), "band_curl": ("band_curl", 4.0, 1), "band_pullapart": ("band_pullapart", 4.0, 1),
    "band_row": ("band_row", 4.0, 1), "wall_pushup": ("wall_pushup", 4.0, 1), "wall_angels": ("wall_angels", 4.0, 1),
    "chin_tucks": ("chin_tucks", 4.0, 1), "cat_cow": ("cat_cow", 6.0, 1), "thoracic_ext_towel": ("thoracic_ext_towel", 6.0, 1),
    "doorway_chest": ("doorway_chest", 14.0, 0), "childs_pose": ("childs_pose", 8.0, 0), "hip_mobility": ("hip_mobility", 6.0, 1),
    "low_impact_dance": ("low_impact_dance", 4.0, 0), "butterfly": ("butterfly", 8.0, 0), "seated_fold": ("seated_fold", 8.0, 0),
    "diaphragm_breath": ("diaphragm_breath", 6.0, 0), "neck_shoulder": ("neck_shoulder", 14.0, 0), "body_scan": ("body_scan", 8.0, 0),
    "full_stretch": ("full_stretch", 42.0, 0), "lower_stretch": ("lower_stretch", 28.0, 0),
}
# bilateral: left clip, right clip (a trailing __R mirrors the motion)
PAIRS = {
    "reverse_lunge": ("reverse_lunge__R", "reverse_lunge", 4.0, 1), "thread_needle": ("thread_needle__R", "thread_needle", 8.0, 0),
    "bird_dog": ("bird_dog__R", "bird_dog", 4.0, 1), "thoracic_rotation": ("thoracic_rotation", "thoracic_rotation__R", 6.0, 1),
    "side_leg_raise": ("side_leg_raise", "side_leg_raise__R", 4.0, 1), "pallof_press": ("pallof_press", "pallof_press__R", 4.0, 1),
    "side_stretch": ("side_stretch", "side_stretch__R", 6.0, 0), "low_lunge": ("low_lunge__R", "low_lunge", 8.0, 0),
    "supine_twist": ("supine_twist", "supine_twist__R", 8.0, 0),
}


def jobs():
    out = {}
    for ex, (m, period, rpl) in SINGLE.items():
        out[m] = None
    for ex, (l, r, period, rpl) in PAIRS.items():
        out[l] = out[r] = None
    return sorted(out)


def manifest():
    mf = {}
    for ex, (m, period, rpl) in SINGLE.items():
        mf[ex] = {"file": f"{m}.mp4", "period": period, "repsPerLoop": rpl}
    for ex, (l, r, period, rpl) in PAIRS.items():
        mf[ex] = {"left": f"{l}.mp4", "right": f"{r}.mp4", "period": period, "repsPerLoop": rpl}
    return mf


def render(name):
    out = os.path.join(OUT, f"{name}.mp4")
    if os.path.exists(out) and os.path.getsize(out) > 1000:
        return name, "skip"
    env = dict(os.environ, GF_FPS=FPS)
    cmd = ["blender", "-b", os.path.join(ROOT, "studio/character/instructor_mpfb.blend"), "-P",
           os.path.join(ROOT, "studio/render/clip_render.py"), "--", name, "auto", out + ".tmp.mp4", RES]
    r = subprocess.run(cmd, capture_output=True, text=True, env=env)
    tmp = out + ".tmp.mp4"
    ok = os.path.exists(tmp) and "CLIP" in r.stdout
    if ok:
        os.replace(tmp, out)
    else:
        sys.stderr.write(f"FAILED {name}\n{r.stdout[-600:]}{r.stderr[-300:]}\n")
    return name, "ok" if ok else "FAIL"


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    cmd = sys.argv[1] if len(sys.argv) > 1 else "render"
    with open(os.path.join(OUT, "manifest.json"), "w") as f:
        json.dump(manifest(), f, indent=1)
    with open(os.path.join(ROOT, "src", "data", "clipManifest.ts"), "w") as f:   # typed copy for the app
        f.write("// Generated by studio/clips.py. Rep clips loop once per rep (or `repsPerLoop` reps).\n"
                "export interface ClipInfo { file?: string; left?: string; right?: string; period: number; repsPerLoop: number }\n"
                f"export const clipManifest: Record<string, ClipInfo> = {json.dumps(manifest(), indent=2)}\n")
    if cmd == "render":
        names = sys.argv[2:] or jobs()
        with ThreadPoolExecutor(JOBS) as ex:
            for n, st in ex.map(render, names):
                print(n, st, flush=True)
